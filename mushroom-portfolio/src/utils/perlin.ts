const UNIT = 1.0 / Math.sqrt(2);

const GRADIENT2: Vector2[] =
    [{x: UNIT, y: UNIT}, {x: -UNIT, y: UNIT}, {x: UNIT, y: -UNIT}, {x: -UNIT, y: -UNIT},
    {x: 1, y: 0}, {x: -1, y: 0}, {x: 0, y: 1}, {x: 0, y: -1}]


export function noise(x: number, y: number) {
    const x0 = Math.trunc(x);
    const y0 = Math.trunc(y);

    const ii = x0 & 255;
    const jj = y0 & 255;

    const computePoint = (x: number, y: number, vector: Vector2) => {
        return vector.x * x + vector.y * y;
    }

    const g0 = PERMS[ii + PERMS[jj]] % 8;
    const g1 = PERMS[ii + 1 + PERMS[jj]] % 8;
    const g2 = PERMS[ii + PERMS[jj + 1]] % 8;
    const g3 =  PERMS[ii + 1 + PERMS[jj + 1]] % 8;

    let tempX = x - x0;
    let tempY = y - y0;
    const s = computePoint(tempX, tempY, GRADIENT2[g0]);

    tempX = x - (x0 + 1);
    tempY = y - y0;
    const t = computePoint(tempX, tempY, GRADIENT2[g1]);

    tempX = x - x0;
    tempY = y - (y0 + 1);
    const u = computePoint(tempX, tempY, GRADIENT2[g2]);

    tempX = x - (x0 + 1);
    tempY = y - (y0 + 1);
    const v = computePoint(tempX, tempY, GRADIENT2[g3]);

    // Interpolation

    let tmp = x - x0;
    const Cx = 3 * tmp * tmp - 2 * tmp * tmp * tmp;
    const Li1 = s + Cx * (t - s);
    const Li2 = u + Cx * (v - u);

    tmp = y - y0;
    const Cy = 3 * tmp * tmp - 2 * tmp * tmp * tmp;

    return Li1 + Cy * (Li2 - Li1);
}

export function normalizedNoise(x: number, y: number) {
    return (noise(x, y) + 1) * 0.5;
}